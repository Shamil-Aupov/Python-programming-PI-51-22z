print("Любишь ли ты программировать?")
answer1 = input()
print("Хочешь ли ты стать программистом?")
answer2 = input()

if answer1 == "да" and answer2 == "да":
    print("Ты настоящий фанат кода!")
elif answer1 == "да" and answer2 == "нет":
    print("Кодинг как хобби — это здорово!")
elif answer1 == "нет" and answer2 == "да":
    print("Интересно, что привлекает тебя в программировании?")
else:
    print("Возможно, программирование — не твоё призвание.")