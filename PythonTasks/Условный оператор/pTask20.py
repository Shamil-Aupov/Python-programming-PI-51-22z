print("Ты стоишь у входа в тёмный лес. Куда пойдёшь?")
print("1 — вперёд по тропинке")
print("2 — налево к реке")

choice1 = input()

if choice1 == "1":
    print("Ты идёшь по тропинке и встречаешь развилку.")
    print("1 — направо к пещере")
    print("2 — налево к деревне")
    
    choice2 = input()
    
    if choice2 == "1":
        print("В пещере ты находишь сундук с сокровищами!")
        print("КОНЦОВКА: Богатство")
    else:
        print("В деревне тебя встречают дружелюбные жители.")
        print("КОНЦОВКА: Новые друзья")
else:
    print("Ты подходишь к реке и видишь лодку.")
    print("1 — сесть в лодку и плыть")
    print("2 — вернуться в лес")
    
    choice2 = input()
    
    if choice2 == "1":
        print("Лодка несёт тебя к волшебному острову!")
        print("КОНЦОВКА: Приключения")
    else:
        print("Ты решаешь вернуться, но теряешься в лесу.")
        print("КОНЦОВКА: Потерянный")